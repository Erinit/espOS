#define COLOR_BLUE    0x001F
#define COLOR_YELLOW  0xFFE0
#define COLOR_CYAN    0x07FF
#define COLOR_MAGENTA 0xF81F
#define COLOR_GRAY    0x8410

// Draw a filled rectangle anywhere on the screen
void st7789_draw_rect(unsigned short x, unsigned short y, unsigned short w, unsigned short h, unsigned short color) {
    // 1. Set the specific window we want to draw inside
    st7789_send_command(0x2A); 
    st7789_send_data(x >> 8); st7789_send_data(x & 0xFF); 
    st7789_send_data((x + w - 1) >> 8); st7789_send_data((x + w - 1) & 0xFF); 

    st7789_send_command(0x2B); 
    st7789_send_data(y >> 8); st7789_send_data(y & 0xFF); 
    st7789_send_data((y + h - 1) >> 8); st7789_send_data((y + h - 1) & 0xFF); 

    // 2. Command the screen to prepare for pixel data
    st7789_send_command(0x2C); 
    
    // 3. Blast the exact number of pixels needed to fill the box
    GPIO_OUT_W1TC_REG = (1 << PIN_CS); 
    GPIO_OUT_W1TS_REG = (1 << PIN_DC); 

    unsigned char ch = color >> 8;
    unsigned char cl = color & 0xFF;

    for (unsigned int i = 0; i < (w * h); i++) {
        spi_send_byte(ch);
        spi_send_byte(cl);
    }
    
    GPIO_OUT_W1TS_REG = (1 << PIN_CS); 
}

