static inline unsigned int get_ccount(void) {
    unsigned int ccount;
    __asm__ __volatile__("rsr %0, ccount" : "=a"(ccount));
    return ccount;
}

void delay_us(unsigned int us) {
    unsigned int start = get_ccount();
    unsigned int cycles = us * 80; 
    while (get_ccount() - start < cycles);
}

// --- RAW GPIO REGISTERS ---
#define GPIO_ENABLE_W1TS_REG (*(volatile unsigned int *)0x3FF44024)
#define GPIO_OUT_W1TS_REG    (*(volatile unsigned int *)0x3FF44008) // Drive HIGH
#define GPIO_OUT_W1TC_REG    (*(volatile unsigned int *)0x3FF4400C) // Drive LOW

// --- WIRING DEFINITIONS ---
#define PIN_DC   2
#define PIN_RST  4
#define PIN_CS   5
#define PIN_CLK  18
#define PIN_MOSI 23

// --- THE SOFTWARE SPI ENGINE ---
void spi_init() {
    // Force all 5 pins to act as standard outputs
    GPIO_ENABLE_W1TS_REG = (1 << PIN_CLK) | (1 << PIN_MOSI) | (1 << PIN_DC) | (1 << PIN_RST) | (1 << PIN_CS);
    
    // Set Idle State: CS HIGH (Deactivated), CLK LOW
    GPIO_OUT_W1TS_REG = (1 << PIN_CS);
    GPIO_OUT_W1TC_REG = (1 << PIN_CLK);
}

void spi_send_byte(unsigned char data) {
    // Manually blast 8 bits, Most-Significant-Bit first
    for (int i = 0; i < 8; i++) {
        if (data & 0x80) {
            GPIO_OUT_W1TS_REG = (1 << PIN_MOSI); // Data HIGH
        } else {
            GPIO_OUT_W1TC_REG = (1 << PIN_MOSI); // Data LOW
        }
        data <<= 1;
        
        // Pulse the Clock Pin HIGH then LOW
        GPIO_OUT_W1TS_REG = (1 << PIN_CLK);
        GPIO_OUT_W1TC_REG = (1 << PIN_CLK);
    }
}

// --- ST7789 DRIVER ---
#define COLOR_RED 0xF800

void st7789_send_command(unsigned char cmd) {
    GPIO_OUT_W1TC_REG = (1 << PIN_CS); // Lock Sync
    GPIO_OUT_W1TC_REG = (1 << PIN_DC); // Command Mode
    spi_send_byte(cmd);
    GPIO_OUT_W1TS_REG = (1 << PIN_CS); // Release Sync
}

void st7789_send_data(unsigned char data) {
    GPIO_OUT_W1TC_REG = (1 << PIN_CS); // Lock Sync
    GPIO_OUT_W1TS_REG = (1 << PIN_DC); // Data Mode
    spi_send_byte(data);
    GPIO_OUT_W1TS_REG = (1 << PIN_CS); // Release Sync
}

void st7789_init() {
    // 1. Hard Hardware Reset
    GPIO_OUT_W1TC_REG = (1 << PIN_RST); 
    delay_us(50000); 
    GPIO_OUT_W1TS_REG = (1 << PIN_RST); 
    delay_us(150000); 

    // 2. Software Wakeup
    st7789_send_command(0x01); // SWRESET
    delay_us(150000);
    st7789_send_command(0x11); // SLPOUT
    delay_us(500000);          

    // 3. 16-bit Color Mode
    st7789_send_command(0x3A); 
    st7789_send_data(0x55);    

    // 4. Memory Orientation
    st7789_send_command(0x36); 
    st7789_send_data(0x00);    

    // 5. Inversion Hack
    st7789_send_command(0x20); 

    // 6. Display ON
    st7789_send_command(0x29); 
    delay_us(100000);
}

void st7789_fill_screen(unsigned short color) {
    // Define the drawing window (0,0 to 239,319)
    st7789_send_command(0x2A); 
    st7789_send_data(0); st7789_send_data(0); 
    st7789_send_data(239 >> 8); st7789_send_data(239 & 0xFF); 

    st7789_send_command(0x2B); 
    st7789_send_data(0); st7789_send_data(0); 
    st7789_send_data(319 >> 8); st7789_send_data(319 & 0xFF); 

    st7789_send_command(0x2C); // Memory Write
    
    // Blast 153,600 bytes continuously 
    GPIO_OUT_W1TC_REG = (1 << PIN_CS); // Keep CS LOW for the entire transmission
    GPIO_OUT_W1TS_REG = (1 << PIN_DC); // Data Mode

    unsigned char ch = color >> 8;
    unsigned char cl = color & 0xFF;

    for (unsigned int i = 0; i < (240 * 320); i++) {
        spi_send_byte(ch);
        spi_send_byte(cl);
    }
    
    GPIO_OUT_W1TS_REG = (1 << PIN_CS); // End Transmission
}

